using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace VYaml.SourceGenerator;

// Emits the per-assembly module-initializer registration file. Registering every
// [YamlObject] formatter (and the closed generic formatters harvested from the member
// graph and [assembly: YamlSerializable] roots) from statically reachable code is what
// makes VYaml work under Native AOT / trimming: nothing is looked up via reflection, so
// nothing can be trimmed away, and the value-type generic instantiations are compiled
// into the binary. On the JIT the module initializer runs lazily, and GeneratedResolver's
// reflection fallback covers the gap exactly as before.
static class RegistrationEmitter
{
    public const string ModuleInitializerAttributePolyfill =
        """
        // <auto-generated />
        // ModuleInitializerAttribute polyfill for target frameworks without it.
        // The compiler recognizes the attribute by its full name; module initializers
        // themselves run on every supported runtime.
        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]
            internal sealed class ModuleInitializerAttribute : global::System.Attribute
            {
            }
        }
        """;

    // Compilation.GetTypeByMetadataName is not used: it ignores accessibility, so an internal
    // polyfill in a referenced assembly (e.g. PolySharp's in VYaml.dll for netstandard2.1)
    // suppresses this polyfill and the [ModuleInitializer] usage fails with CS0122.
    // Compilation.GetTypesByMetadataName is not used: it requires Roslyn 4.2+.
    public static bool NeedsModuleInitializerPolyfill(Compilation compilation)
    {
        const string metadataName = "System.Runtime.CompilerServices.ModuleInitializerAttribute";
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols.Prepend(compilation.Assembly))
        {
            if (assembly.GetTypeByMetadataName(metadataName) is { } type &&
                compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            {
                return false;
            }
        }
        return true;
    }

    public static string Emit(string assemblyName, IEnumerable<string> statements)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS0612 // Obsolete member usage");
        builder.AppendLine("#pragma warning disable CS0618 // Obsolete member usage");
        builder.AppendLine("#pragma warning disable CS8714 // Nullability of type argument doesn't match 'notnull' constraint");
        builder.AppendLine();
        builder.AppendLine("namespace VYaml.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    internal static class VYamlRegistration_" + SanitizeAssemblyName(assemblyName));
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        [global::VYaml.Annotations.Preserve]");
        builder.AppendLine("        internal static void Register()");
        builder.AppendLine("        {");
        foreach (var statement in statements)
        {
            builder.Append("            ").AppendLine(statement);
        }
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("#pragma warning restore CS0612");
        builder.AppendLine("#pragma warning restore CS0618");
        builder.AppendLine("#pragma warning restore CS8714");
        return builder.ToString();
    }

    static string SanitizeAssemblyName(string assemblyName)
    {
        var builder = new StringBuilder(assemblyName.Length + 1);
        if (assemblyName.Length > 0 && char.IsDigit(assemblyName[0]))
        {
            builder.Append('_');
        }
        foreach (var c in assemblyName)
        {
            builder.Append(char.IsLetterOrDigit(c) ? c : '_');
        }
        return builder.ToString();
    }
}
